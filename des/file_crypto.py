import os
import sys
from des import encrypt_des, decrypt_des
import time
import hashlib


class FileCrypto:
    def __init__(self):
        self.version = "1.0"
        self.author = "Student Cybersecurity"
        self.supported_formats = ['.txt', '.md',
                                  '.py', '.js', '.html', '.css', '.json']

    def validate_key(self, key):
        """Kiểm tra tính hợp lệ của key"""
        if not key:
            return False, "Key không được để trống"
        if len(key) < 8:
            return False, "Key phải có ít nhất 8 ký tự"
        if len(key) > 64:
            return False, "Key không được quá 64 ký tự"
        return True, "Key hợp lệ"

    def get_file_info(self, filepath):
        """Lấy thông tin file"""
        if not os.path.exists(filepath):
            return None

        stat = os.stat(filepath)
        return {
            'size': stat.st_size,
            'modified': time.ctime(stat.st_mtime),
            'extension': os.path.splitext(filepath)[1],
            'name': os.path.basename(filepath)
        }

    def encrypt_file(self, input_file, output_file, key):
        """
        Mã hóa file

        Args:
            input_file (str): Đường dẫn file đầu vào
            output_file (str): Đường dẫn file đầu ra
            key (str): Key mã hóa

        Returns:
            tuple: (success, message, stats)
        """
        try:
            # Kiểm tra key
            valid, msg = self.validate_key(key)
            if not valid:
                return False, msg, None

            # Kiểm tra file đầu vào
            if not os.path.exists(input_file):
                return False, f"File không tồn tại: {input_file}", None

            file_info = self.get_file_info(input_file)

            # Đọc file
            try:
                with open(input_file, 'r', encoding='utf-8') as f:
                    content = f.read()
            except UnicodeDecodeError:
                # Thử với encoding khác
                with open(input_file, 'r', encoding='latin-1') as f:
                    content = f.read()

            if not content:
                return False, "File trống hoặc không đọc được", None

            # Mã hóa
            start_time = time.time()
            encrypted_content = encrypt_des(content, key)
            end_time = time.time()

            # Tạo metadata
            metadata = {
                'original_filename': file_info['name'],
                'original_size': len(content),
                'encryption_time': time.strftime('%Y-%m-%d %H:%M:%S'),
                # Chỉ lưu hash để verify
                'key_hash': hashlib.sha256(key.encode()).hexdigest()[:16],
                'version': self.version
            }

            # Tạo nội dung file mã hóa với metadata
            final_content = f"""# DES ENCRYPTED FILE
# Generated by FileCrypto v{self.version}
# Original: {metadata['original_filename']}
# Size: {metadata['original_size']} bytes
# Time: {metadata['encryption_time']}
# Key Hash: {metadata['key_hash']}
# ==========================================
{encrypted_content}"""

            # Ghi file đã mã hóa
            with open(output_file, 'w', encoding='utf-8') as f:
                f.write(final_content)

            # Thống kê
            stats = {
                'original_size': len(content),
                'encrypted_size': len(final_content),
                'compression_ratio': len(final_content) / len(content),
                'time_taken': end_time - start_time,
                'key_length': len(key),
                'file_info': file_info,
                'metadata': metadata
            }

            return True, "Mã hóa thành công", stats

        except Exception as e:
            return False, f"Lỗi: {str(e)}", None

    def decrypt_file(self, input_file, output_file, key):
        """
        Giải mã file

        Args:
            input_file (str): Đường dẫn file mã hóa
            output_file (str): Đường dẫn file sau giải mã
            key (str): Key giải mã

        Returns:
            tuple: (success, message, stats)
        """
        try:
            # Kiểm tra key
            valid, msg = self.validate_key(key)
            if not valid:
                return False, msg, None

            # Kiểm tra file đầu vào
            if not os.path.exists(input_file):
                return False, f"File không tồn tại: {input_file}", None

            # Đọc file mã hóa
            with open(input_file, 'r', encoding='utf-8') as f:
                full_content = f.read()

            if not full_content:
                return False, "File trống", None

            # Phân tích metadata và nội dung
            lines = full_content.split('\n')

            # Tìm dòng phân cách
            separator_index = -1
            metadata = {}

            for i, line in enumerate(lines):
                if line.strip() == '# ==========================================':
                    separator_index = i
                    break
                elif line.startswith('# Original:'):
                    metadata['original_filename'] = line.split(': ', 1)[1]
                elif line.startswith('# Size:'):
                    metadata['original_size'] = line.split(': ', 1)[1]
                elif line.startswith('# Time:'):
                    metadata['encryption_time'] = line.split(': ', 1)[1]
                elif line.startswith('# Key Hash:'):
                    metadata['key_hash'] = line.split(': ', 1)[1]

            if separator_index == -1:
                return False, "File không phải format mã hóa hợp lệ", None

            # Lấy nội dung mã hóa
            encrypted_content = '\n'.join(lines[separator_index + 1:])

            # Verify key (optional)
            key_hash = hashlib.sha256(key.encode()).hexdigest()[:16]
            if 'key_hash' in metadata and metadata['key_hash'] != key_hash:
                print(f"⚠️  Warning: Key hash không khớp. Có thể key không đúng.")

            # Giải mã
            start_time = time.time()
            decrypted_content = decrypt_des(encrypted_content, key)
            end_time = time.time()

            # Ghi file đã giải mã
            with open(output_file, 'w', encoding='utf-8') as f:
                f.write(decrypted_content)

            # Thống kê
            stats = {
                'encrypted_size': len(full_content),
                'decrypted_size': len(decrypted_content),
                'time_taken': end_time - start_time,
                'key_length': len(key),
                'metadata': metadata
            }

            return True, "Giải mã thành công", stats

        except Exception as e:
            return False, f"Lỗi: {str(e)}", None

    def print_stats(self, stats, operation):
        """In thống kê chi tiết"""
        if not stats:
            return

        print(f"\n📊 THỐNG KÊ {operation.upper()}:")
        print("="*50)

        if operation == "mã hóa":
            print(
                f"📄 File gốc: {stats.get('file_info', {}).get('name', 'N/A')}")
            print(f"📏 Kích thước gốc: {stats['original_size']:,} ký tự")
            print(f"🔒 Kích thước mã hóa: {stats['encrypted_size']:,} ký tự")
            print(f"📈 Tỷ lệ nén: {stats['compression_ratio']:.2f}")

            if 'metadata' in stats:
                print(
                    f"🕒 Thời gian mã hóa: {stats['metadata']['encryption_time']}")
                print(f"🔑 Key hash: {stats['metadata']['key_hash']}")

        else:
            print(
                f"🔒 Kích thước file mã hóa: {stats['encrypted_size']:,} ký tự")
            print(
                f"📄 Kích thước sau giải mã: {stats['decrypted_size']:,} ký tự")

            if 'metadata' in stats:
                print(
                    f"📁 File gốc: {stats['metadata'].get('original_filename', 'N/A')}")
                print(
                    f"🕒 Thời gian mã hóa: {stats['metadata'].get('encryption_time', 'N/A')}")

        print(f"🔑 Độ dài key: {stats['key_length']} ký tự")
        print(f"⏱️  Thời gian xử lý: {stats['time_taken']:.4f} giây")


