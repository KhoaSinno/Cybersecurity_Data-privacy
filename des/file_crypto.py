        decrypted_file = f"{sample_file}.decrypted"

        # Mã hóa
        print(f"🔐 Mã hóa {sample_file}...")
        success, message, stats = crypto.encrypt_file(
            sample_file, encrypted_file, key)

        if success:
            print(f"✅ {message}")
            crypto.print_stats(stats, "mã hóa")
        else:
            print(f"❌ {message}")
            continue

        # Giải mã
        print(f"\n🔓 Giải mã {encrypted_file}...")
        success, message, stats = crypto.decrypt_file(
            encrypted_file, decrypted_file, key)

        if success:
            print(f"✅ {message}")
            crypto.print_stats(stats, "giải mã")

            # So sánh file gốc và file đã giải mã
            with open(sample_file, 'r', encoding='utf-8') as f1, \
                    open(decrypted_file, 'r', encoding='utf-8') as f2:
                original = f1.read()
                decrypted = f2.read()

            integrity_check = original == decrypted
            print(f"\n🔍 KIỂM TRA TÍNH TOÀN VẸN:")
            print(f"{'✅' if integrity_check else '❌'} File gốc và file giải mã: {'GIỐNG NHAU' if integrity_check else 'KHÁC NHAU'}")

        else:
            print(f"❌ {message}")


